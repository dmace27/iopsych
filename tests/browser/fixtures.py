def synthetic_credentials(environment):
    """Short-lived seed-only JWTs for the existing token/session exchange.

    No endpoint or verifier bypass is installed. Keys are generated by the owned
    runner and credentials never leave its process tree or temporary artifacts.
    """
    import base64
    import hashlib
    import hmac
    import json
    import time

    from app.database.seed import ALPHA_ORGANIZATION_ID, BEACON_ORGANIZATION_ID

    if environment.get("BROWSER_E2E_OWNED") != "1":
        raise RuntimeError("Credentials require the isolated runner")

    def segment(value):
        return base64.urlsafe_b64encode(json.dumps(value).encode()).rstrip(b"=").decode()

    result = {}
    for name, subject, organization in (
        ("RECRUITER", "synthetic-alpha-recruiter", ALPHA_ORGANIZATION_ID),
        ("MANAGER", "synthetic-beacon-manager", BEACON_ORGANIZATION_ID),
        ("ADMIN", "synthetic-browser-admin", ALPHA_ORGANIZATION_ID),
    ):
        now = int(time.time())
        content = (
            segment({"alg": "HS256", "typ": "JWT"})
            + "."
            + segment(
                {
                    "sub": subject,
                    "organization_id": str(organization),
                    "iss": environment["AUTH_JWT_ISSUER"],
                    "aud": environment["AUTH_JWT_AUDIENCE"],
                    "iat": now,
                    "nbf": now,
                    "exp": now + 3600,
                }
            )
        )
        signature = hmac.new(
            environment["AUTH_JWT_SECRET"].encode(), content.encode(), hashlib.sha256
        ).digest()
        result[f"BROWSER_E2E_{name}"] = (
            content + "." + base64.urlsafe_b64encode(signature).rstrip(b"=").decode()
        )
    return result


