"""Allowlisted, bounded HTTP completion telemetry with server-owned correlation."""

import json
import logging
import os
import re
from collections.abc import Sequence
from time import monotonic
from uuid import UUID, uuid4

from fastapi.routing import iter_route_contexts
from starlette.routing import BaseRoute
from starlette.types import ASGIApp, Message, Receive, Scope, Send

_LOGGER = logging.getLogger(__name__)
_METHODS = frozenset(
    {"GET", "HEAD", "POST", "PUT", "DELETE", "CONNECT", "OPTIONS", "TRACE", "PATCH"}
)
_RELEASE = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,63}")
_REQUEST_ID_KEY = "telemetry_request_id"
_MAX_DURATION_MS = 86_400_000


def correlation_headers(scope: Scope) -> dict[str, str]:
    """Return only the UUID generated by this middleware for outer error handlers."""
    request_id = scope.get(_REQUEST_ID_KEY)
    return {"X-Request-ID": str(request_id)} if isinstance(request_id, UUID) else {}


class CompletionTelemetryMiddleware:
    """Record HTTP completion without accessing request content or identity.

    Route objects and their templates are snapshotted from application configuration.
    Unknown and pre-routing failures share a fixed unmatched label.
    """

    def __init__(self, app: ASGIApp, *, routes: Sequence[BaseRoute]) -> None:
        self.app = app
        _LOGGER.setLevel(logging.INFO)
        if not _LOGGER.hasHandlers():
            _LOGGER.addHandler(logging.StreamHandler())
        self.routes: dict[int, str] = {}
        for context in iter_route_contexts(routes):
            path = context.path
            if isinstance(path, str) and len(path) <= 256:
                key = id(context.original_route)
                previous = self.routes.get(key, path)
                self.routes[key] = path if previous == path else "unmatched"
        release = os.environ.get("IOPSYCH_RELEASE_ID", "")
        self.release_id = release if _RELEASE.fullmatch(release) else "unknown"

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return

        request_id = uuid4()
        scope[_REQUEST_ID_KEY] = request_id
        started = monotonic()
        status_class = "unknown"
        completed = False

        async def correlated_send(message: Message) -> None:
            nonlocal status_class, completed
            if message["type"] == "http.response.start":
                status = message["status"]
                status_class = f"{status // 100}xx" if 100 <= status < 600 else "unknown"
                message = dict(message)
                message["headers"] = [
                    (key, value)
                    for key, value in message.get("headers", [])
                    if key.lower() != b"x-request-id"
                ] + [(b"x-request-id", str(request_id).encode("ascii"))]
            await send(message)
            if message["type"] == "http.response.body" and not message.get("more_body", False):
                completed = True

        try:
            await self.app(scope, receive, correlated_send)
        except Exception:
            if status_class == "unknown":
                status_class = "5xx"
            raise
        except BaseException:
            status_class = "unknown"
            raise
        finally:
            if not completed and status_class != "5xx":
                status_class = "unknown"
            method = scope.get("method", "")
            record = {
                "event": "request_completed",
                "request_id": str(request_id),
                "method": method if method in _METHODS else "OTHER",
                "route": self.routes.get(id(scope.get("route")), "unmatched"),
                "status_class": status_class,
                "duration_ms": min(_MAX_DURATION_MS, max(0, int((monotonic() - started) * 1000))),
                "release_id": self.release_id,
            }
            _LOGGER.info(json.dumps(record, separators=(",", ":")).replace("/", r"\/"))
